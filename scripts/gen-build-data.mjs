#!/usr/bin/env node
// gen-build-data.mjs — emit data/build.yaml with site activity stats
// and a "verified by" wall of contributors who touched the trust data
// (data/stages/*.yaml + data/countries.yaml).
//
// Read by Hugo via hugo.Data.build (footer activity ribbon + /freshness/
// + /sources/ contributor wall). Runs in CI before `hugo build`.
// data/build.yaml is gitignored.

import { execSync } from 'node:child_process';
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';

function git(...args) {
  try {
    return execSync(`git ${args.join(' ')}`, { encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

const lastCommitISO = git('log', '-1', '--format=%cI');
const lastCommitDays = lastCommitISO
  ? Math.floor((Date.now() - new Date(lastCommitISO).getTime()) / 86_400_000)
  : 0;

const contributors = git('shortlog', '-sn', 'HEAD')
  .split('\n')
  .filter((l) => l.trim().length > 0);
const contributorCount = contributors.length;

const recentUpdatesRaw = git('log', '--since="90 days ago"', '--pretty=format:%h', '--', 'content/', 'data/');
const recentUpdates = recentUpdatesRaw ? recentUpdatesRaw.split('\n').filter(Boolean).length : 0;

const starCount = await (async () => {
  try {
    const [owner, repo] = (process.env.GITHUB_REPOSITORY || '7nolikov/ohmoveagain').split('/');
    const res = await fetch(`https://api.github.com/repos/${owner}/${repo}`, {
      headers: { 'Accept': 'application/vnd.github.v3+json' }
    });
    if (res.ok) return (await res.json()).stargazers_count || 0;
  } catch {}
  return 0;
})();

// ---- "Verified by" wall: contributors who touched trust data ----

const aliasesPath = 'data/contributor_aliases.json';
const aliases = existsSync(aliasesPath)
  ? JSON.parse(readFileSync(aliasesPath, 'utf8'))
  : {};

// Match "<num>+<username>@users.noreply.github.com" or
// "<username>@users.noreply.github.com" — GitHub's privacy emails.
function ghFromNoreply(email) {
  const m1 = email.match(/^(\d+)\+([\w-]+)@users\.noreply\.github\.com$/i);
  if (m1) return m1[2];
  const m2 = email.match(/^([\w-]+)@users\.noreply\.github\.com$/i);
  if (m2) return m2[1];
  return null;
}

function isBot(name, email) {
  if (!name) return false;
  const n = name.toLowerCase();
  if (n.endsWith('[bot]')) return true;
  if (n === 'dependabot' || n === 'github-actions' || n === 'renovate') return true;
  if (email && email.toLowerCase().includes('[bot]@')) return true;
  return false;
}

const trustPaths = ['data/stages', 'data/countries.yaml'];
const logLines = git(
  'log',
  "--pretty=format:%H%x09%an%x09%ae%x09%cI",
  '--',
  ...trustPaths
).split('\n').filter(Boolean);

const byEmail = new Map();
for (const line of logLines) {
  const [hash, name, email, dateISO] = line.split('\t');
  if (!email || isBot(name, email)) continue;
  const key = email.toLowerCase();
  if (!byEmail.has(key)) {
    byEmail.set(key, {
      name,
      email,
      commits: 0,
      latestCommit: dateISO,
    });
  }
  const e = byEmail.get(key);
  e.commits += 1;
  if (dateISO > e.latestCommit) e.latestCommit = dateISO;
}

const verifiedBy = [];
for (const e of byEmail.values()) {
  const gh = aliases[e.email] || aliases[e.email.toLowerCase()] || ghFromNoreply(e.email);
  verifiedBy.push({
    name: e.name,
    ghUsername: gh || '',
    commits: e.commits,
    latestCommit: e.latestCommit,
    avatarUrl: gh ? `https://github.com/${gh}.png?size=80` : '',
    profileUrl: gh ? `https://github.com/${gh}` : '',
  });
}
verifiedBy.sort((a, b) => b.commits - a.commits || a.name.localeCompare(b.name));

// ---- Emit YAML manually (no dep needed) ----

function yamlEscape(s) {
  if (s == null) return '""';
  const str = String(s);
  if (/^[A-Za-z0-9_./@:+-]+$/.test(str)) return str;
  return '"' + str.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

let verifiedByYaml = '';
for (const v of verifiedBy) {
  verifiedByYaml += '  - name: ' + yamlEscape(v.name) + '\n';
  verifiedByYaml += '    ghUsername: ' + yamlEscape(v.ghUsername) + '\n';
  verifiedByYaml += '    commits: ' + v.commits + '\n';
  verifiedByYaml += '    latestCommit: ' + yamlEscape(v.latestCommit) + '\n';
  verifiedByYaml += '    avatarUrl: ' + yamlEscape(v.avatarUrl) + '\n';
  verifiedByYaml += '    profileUrl: ' + yamlEscape(v.profileUrl) + '\n';
}

const out = [
  '# Auto-generated by scripts/gen-build-data.mjs — do not edit.',
  `generatedAt: "${new Date().toISOString()}"`,
  'stats:',
  `  lastCommitDate: "${lastCommitISO}"`,
  `  lastCommitDays: ${lastCommitDays}`,
  `  contributorCount: ${contributorCount}`,
  `  recentUpdates: ${recentUpdates}`,
  `  starCount: ${starCount}`,
  'verifiedBy:',
  verifiedByYaml || '  []',
].join('\n');

mkdirSync('data', { recursive: true });
writeFileSync('data/build.yaml', out);
console.log(
  `Wrote data/build.yaml — ${contributorCount} contributors, last commit ${lastCommitDays}d ago, ${recentUpdates} updates in 90d, ${verifiedBy.length} verified-by entries.`
);
